# Hand-assembled fixtures: stub boot ROMs, a no-MBC ROM, an MBC5 ROM, a symbol file.
import sys, os
out = sys.argv[1]

def boot(size):
    b = bytearray([0x00]) * size
    b[0:3] = bytes([0x31, 0xFE, 0xFF])          # ld sp,$fffe
    b[0xFC:0x100] = bytes([0x3E, 0x01, 0xE0, 0x50])  # ld a,1 ; ldh ($50),a -> pc=$0100
    return b

def program(rom, mbc):
    rom[0x100:0x104] = bytes([0x00, 0xC3, 0x50, 0x01])
    rom[0x134:0x13C] = b"PROBEMAP"
    rom[0x147] = 0x19 if mbc else 0x00
    rom[0x148] = 0x01 if mbc else 0x00
    code = [0xF3, 0x31, 0xFE, 0xFF, 0xAF, 0xEA, 0x00, 0xC0, 0xEA, 0x01, 0xC0, 0xEA, 0x02, 0xC0,
            0x3E, 0x01, 0xE0, 0xFF, 0x3E, 0x91, 0xE0, 0x40]          # ...ie=1, lcdc=$91
    if mbc:
        code += [0x3E, 0x02, 0xEA, 0x00, 0x20]                       # ld a,2 ; ld ($2000),a
    code += [0xFB]                                                   # ei
    loop = 0x150 + len(code)
    code += [0xFA, 0x00, 0xC0, 0x3C, 0xEA, 0x00, 0xC0, 0xCD, 0x00, 0x02, 0x76, 0x00]
    jr_from = 0x150 + len(code) + 2
    code += [0x18, (loop - jr_from) & 0xFF]
    rom[0x150:0x150 + len(code)] = bytes(code)
    rom[0x200:0x208] = bytes([0x21, 0x01, 0xC0, 0x34, 0xCD, 0x10, 0x02, 0xC9])
    rom[0x210:0x216] = bytes([0x06, 0x42, 0x40, 0x0E, 0x07, 0xC9])   # ld b,$42 ; ld b,b ; ld c,7 ; ret
    rom[0x40:0x43] = bytes([0xC3, 0x20, 0x03])
    rom[0x320:0x32A] = bytes([0xF5, 0xFA, 0x02, 0xC0, 0x3C, 0xEA, 0x02, 0xC0, 0xF1, 0xD9])
    c = 0
    for i in range(0x134, 0x14D): c = (c - rom[i] - 1) & 0xFF
    rom[0x14D] = c
    return loop

rom = bytearray(0x8000); loop = program(rom, False)
open(os.path.join(out, "basic.gb"), "wb").write(rom)
rom = bytearray(0x10000); program(rom, True)
for n in (1, 2, 3):
    rom[n * 0x4000:(n + 1) * 0x4000] = bytes([0xB0 | n]) * 0x4000
open(os.path.join(out, "mbc5.gb"), "wb").write(rom)
open(os.path.join(out, "dmg_stub.bin"), "wb").write(boot(0x100))
open(os.path.join(out, "cgb_stub.bin"), "wb").write(boot(0x900))
open(os.path.join(out, "basic.sym"), "w").write(
    f"00:{loop:04x} loop\n00:0200 func1\n00:0210 func2\n00:0320 vblank_handler\n"
    "00:c000 counter\n00:c001 a\n00:c002 ac\n01:4000 bank1_start\n02:4000 bank2_start\n; comment line\n")
print(hex(loop))
